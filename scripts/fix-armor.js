  const end = s.indexOf('},{', start)
  let span = s.slice(start, end < 0 ? start + 600 : end)
  const sRe = /stats:\[\[[\s\S]*?\]\](?=[,;])/
  const oRe = /obtain:"[^"]*"/
  if (!sRe.test(span) || !oRe.test(span)) { console.log('SPAN-FAIL', id, JSON.stringify(span.slice(0, 120))); process.exitCode = 1; continue }
