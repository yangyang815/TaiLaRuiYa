// ---------- 变换 ----------
C.classes.forEach((c) => {
  const nodes = c.nodes;
  const out = [];
  nodes.forEach((nd) => {
    // ① 灾厄双邪前之后插入 骷髅王前；血肉墙前（含骷髅王）改名
    if (nd.n === "灾厄双邪前") {
      out.push(nd);
      out.push(NEW_NODES["骷髅王前"][c.id]);
      return;
    }
    if (nd.n === "血肉墙前（含骷髅王）") {
      out.push(Object.assign({}, nd, { n: "血肉墙前" }));
      return;
    }
    // ② 困难模式开局之后插入两个机械节点
    if (nd.n === "困难模式开局") {
      out.push(nd);
      out.push(NEW_NODES["任意一个机械Boss后"][c.id]);
      out.push(NEW_NODES["任意两个机械Boss后"][c.id]);
      return;
    }
    // ③ 交换 月亮领主前 ↔ 四柱前（输出顺序：四柱前 → 月亮领主前），四柱前改名
    if (nd.n === "月亮领主前") {
      out.push(Object.assign({}, nodes.find((x) => x.n === "四柱前（决战月主）"), { n: "四柱前" }));
      out.push(nd);
      return;
    }
    if (nd.n === "四柱前（决战月主）") return; // 已在 月亮领主前 位置输出
    // ④ 犽戎前之后插入两个至尊女巫/星流巨械节点
    if (nd.n === "犽戎前") {
      out.push(nd);
      out.push(NEW_NODES["至尊女巫和星流巨械前"][c.id]);
      out.push(NEW_NODES["至尊女巫或星流巨械后"][c.id]);
      return;
    }
    out.push(nd);
  });
  c.nodes = out;
});

