const esc = (s) => String(s || "").replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")
let hit = 0
cal.items.forEach((e) => {
  const p = PATCH[e.n]
  if (!p) return
  hit++
  if (p.tip) e.tip = p.tip
  if (p.dts) e.dts = p.dts
})

const lines = cal.items.map((e) =>
  '    { id:"' + esc(e.id) + '", n:"' + esc(e.n) + '", en:"' + esc(e.en) + '", cat:"' + e.cat + '"' +
  (e.cls ? ', cls:"' + e.cls + '"' : "") +
  (e.stg ? ', stg:"' + e.stg + '"' : "") +
  (e.boss ? ', boss:"' + e.boss + '"' : "") +
  (e.rate ? ', rate:"' + e.rate + '"' : "") +
  (e.dts ? ", dts:" + JSON.stringify(e.dts) : "") +
  ', tip:"' + esc(e.tip) + '" }'
)
