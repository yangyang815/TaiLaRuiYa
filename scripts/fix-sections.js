const fs = require('fs')

let total = 0
function patchFile (fp, fn) {
  let s = fs.readFileSync(fp, 'utf8')
  const ns = fn(s)
  if (ns !== s) { fs.writeFileSync(fp, ns); total++ } else console.log('NOCHANGE:', fp)
}
function rep (s, o, nw) {
  if (!s.includes(o)) { console.log('  MISS:', String(o).slice(0, 50)); return s }
  return s.split(o).join(nw)
}

